#!/usr/bin/env bash
# k3s/base/pki/certificates.yaml from pki/identities.txt: one cert-manager Certificate per identity pki.sh issues, shaped as
# its leaves are (CN = the identity, server and client auth, PKCS8 RSA-2048 key, a year, SANs: the name, its in-cluster
# names, localhost, 127.0.0.1 and the extra names of the line). tests/k3s-pki.test.sh fails when the committed file differs.
#   k3s/scripts/gen-certificates.sh > k3s/base/pki/certificates.yaml
# A ${OJ_PUBLIC_HOST} on a line is not a name here: the host the browser sees is the ingress's certificate (Let's Encrypt on
# the server), not an identity's.
set -euo pipefail
cd "$(dirname "$0")/../.."

echo "# Generated by k3s/scripts/gen-certificates.sh from pki/identities.txt: edit that file and run the script, not this one."
while read -r id _ extra; do
  case $id in '' | '#'* | rogue) continue ;; esac
  names=("$id" "$id.oj.svc" "$id.oj.svc.cluster.local" localhost)
  for name in $extra; do
    [[ $name == '${'* ]] && continue
    [[ " ${names[*]} " == *" $name "* ]] || names+=("$name")
  done
  cat <<YAML
---
apiVersion: cert-manager.io/v1
kind: Certificate
metadata:
  name: $id
spec:
  secretName: tls-$id
  commonName: $id
  dnsNames:
YAML
  for name in "${names[@]}"; do echo "    - $name"; done
  cat <<YAML
  ipAddresses:
    - 127.0.0.1
  usages:
    - digital signature
    - key encipherment
    - server auth
    - client auth
  duration: 8760h
  renewBefore: 720h
  privateKey:
    algorithm: RSA
    size: 2048
    encoding: PKCS8
    rotationPolicy: Always
  issuerRef:
    group: cert-manager.io
    kind: Issuer
    name: oj-ca
YAML
done < pki/identities.txt
