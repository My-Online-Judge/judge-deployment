#!/usr/bin/env python3
"""Generated parts of k3s/base/data, so they cannot drift from what they copy:

  gen_data.py postgres        three Postgres StatefulSets and Services (identity-db, problem-db, submission-db) and the
                              pg_hba ConfigMap, shaped as docker-compose.yml runs them
  gen_data.py init-scripts    the ConfigMaps of the two init Jobs: kafka/acls.sh, kafka/admin-client.properties,
                              minio/minio-init.sh and minio/policies/*.json, byte for byte

  python3 k3s/scripts/gen_data.py postgres > k3s/base/data/postgres.yaml

tests/k3s-data.test.sh fails when a committed file differs from this output.
"""
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
HEADER = "# Generated by k3s/scripts/gen_data.py {target}: edit its sources (or the script), not this file.\n"

# docker-compose.yml's x-postgres-tls command, and its pg-hba config.
POSTGRES_ARGS = ["postgres", "-c", "timezone=Asia/Ho_Chi_Minh", "-c", "log_timezone=Asia/Ho_Chi_Minh", "-c", "ssl=on",
                 "-c", "ssl_cert_file=/etc/oj/tls/tls.crt", "-c", "ssl_key_file=/etc/oj/tls/tls.key",
                 "-c", "ssl_ca_file=/etc/oj/tls/ca.crt", "-c", "hba_file=/etc/oj/pg_hba.conf"]
PG_HBA = """local   all all                     trust
hostssl all all 0.0.0.0/0           scram-sha-256 clientcert=verify-ca
hostssl all all ::/0                scram-sha-256 clientcert=verify-ca
"""
# database -> the Secret (k3s/scripts/env-to-secrets.sh) holding its POSTGRES_* variables: the .env file of its service
DATABASES = {"identity-db": "env-identity-db", "problem-db": "env-problem", "submission-db": "env-submission"}


def block(text, indent):
    """A YAML literal block of text (every line indented), keeping the file's own lines."""
    lines = text.rstrip("\n").split("\n")
    return "|\n" + "\n".join((" " * indent + line) if line else "" for line in lines)


def postgres():
    out = [HEADER.format(target="postgres")]
    out.append(f"""apiVersion: v1
kind: ConfigMap
metadata:
  name: pg-hba
data:
  pg_hba.conf: {block(PG_HBA, 4)}
""")
    args = "\n".join(f"            - {a}" for a in POSTGRES_ARGS)
    for name, env_secret in DATABASES.items():
        out.append(f"""---
apiVersion: v1
kind: Service
metadata:
  name: {name}
  labels:
    app: {name}
spec:
  selector:
    app: {name}
  ports:
    - name: postgres
      port: 5432
---
apiVersion: apps/v1
kind: StatefulSet
metadata:
  name: {name}
  labels:
    app: {name}
spec:
  serviceName: {name}
  replicas: 1
  selector:
    matchLabels:
      app: {name}
  template:
    metadata:
      labels:
        app: {name}
    spec:
      enableServiceLinks: false
      terminationGracePeriodSeconds: 60
      securityContext:
        runAsUser: 999
        runAsGroup: 999
        runAsNonRoot: true
        fsGroup: 999
        seccompProfile:
          type: RuntimeDefault
      containers:
        - name: postgres
          image: postgres:16
          args:
{args}
          # POSTGRES_DB / POSTGRES_USER / POSTGRES_PASSWORD, from the Secret k3s/scripts/env-to-secrets.sh makes
          envFrom:
            - secretRef:
                name: {env_secret}
          env:
            - name: TZ
              value: Asia/Ho_Chi_Minh
            # the volume's root is not empty on every provisioner: initdb wants a directory of its own
            - name: PGDATA
              value: /var/lib/postgresql/data/pgdata
          ports:
            - name: postgres
              containerPort: 5432
          securityContext:
            allowPrivilegeEscalation: false
            capabilities:
              drop: [ALL]
          resources:
            requests:
              cpu: 50m
              memory: 128Mi
            limits:
              memory: 512Mi
          startupProbe:
            exec:
              command: [sh, -c, 'pg_isready -U "$POSTGRES_USER" -d "$POSTGRES_DB"']
            periodSeconds: 3
            failureThreshold: 60
          readinessProbe:
            exec:
              command: [sh, -c, 'pg_isready -U "$POSTGRES_USER" -d "$POSTGRES_DB"']
            periodSeconds: 5
            timeoutSeconds: 3
          livenessProbe:
            exec:
              command: [sh, -c, 'pg_isready -U "$POSTGRES_USER" -d "$POSTGRES_DB"']
            periodSeconds: 15
            timeoutSeconds: 5
            failureThreshold: 6
          volumeMounts:
            - name: data
              mountPath: /var/lib/postgresql/data
            - name: tls
              mountPath: /etc/oj/tls
              readOnly: true
            - name: pg-hba
              mountPath: /etc/oj/pg_hba.conf
              subPath: pg_hba.conf
              readOnly: true
      volumes:
        # 0640 + fsGroup: root-owned and group-readable, the most Postgres accepts for a key it does not own
        - name: tls
          secret:
            secretName: tls-{name}
            defaultMode: 0640
        - name: pg-hba
          configMap:
            name: pg-hba
  volumeClaimTemplates:
    - metadata:
        name: data
      spec:
        accessModes: [ReadWriteOnce]
        resources:
          requests:
            storage: 5Gi
""")
    return "".join(out)


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return f.read()


def configmap(name, files):
    body = "".join(f"  {key}: {block(read(path), 4)}\n" for key, path in files)
    return f"apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: {name}\ndata:\n{body}"


def init_scripts():
    policies = sorted(os.listdir(os.path.join(ROOT, "minio", "policies")))
    return HEADER.format(target="init-scripts") + configmap("kafka-init-scripts", [
        ("acls.sh", "kafka/acls.sh"), ("admin-client.properties", "kafka/admin-client.properties"),
    ]) + "---\n" + configmap("minio-init-scripts", [("minio-init.sh", "minio/minio-init.sh")]
                             + [(p, f"minio/policies/{p}") for p in policies])


if __name__ == "__main__":
    targets = {"postgres": postgres, "init-scripts": init_scripts}
    if len(sys.argv) != 2 or sys.argv[1] not in targets:
        sys.exit("usage: gen_data.py postgres|init-scripts")
    sys.stdout.write(targets[sys.argv[1]]())
