#!/usr/bin/env python3
"""k3s/base/backup/backup.yaml: the scripts of k3s/backup/ (and backup/lib.sh, the row-count helper compose's backup uses) as a
ConfigMap, the nightly CronJob `backup` and the suspended CronJob `restore-drill`.

  python3 k3s/scripts/gen_backup.py > k3s/base/backup/backup.yaml

tests/k3s-backup.test.sh compares the result with the committed file and the images with compose's and the data layer's.
"""
import glob
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
HEADER = "# Generated by k3s/scripts/gen_backup.py: edit k3s/backup/*.sh (or the script), not this file.\n"


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return f.read()


def block(text, indent):
    lines = text.rstrip("\n").split("\n")
    return "|\n" + "\n".join((" " * indent + line) if line else "" for line in lines)


RESTIC = re.search(r'RESTIC_IMAGE="(restic/restic:[^"]+)"', read("backup/backup.sh")).group(1)
# the images of the data layer: the databases' Postgres, and the MinIO image that has mc (what minio-init runs)
POSTGRES = re.search(r"image: (postgres:\S+)", read("k3s/base/data/postgres.yaml")).group(1)
MINIO = re.search(r"image: (ghcr.io/my-online-judge/minio:\S+)", read("k3s/base/data/init-jobs.yaml")).group(1)

SECURITY = """            allowPrivilegeEscalation: false
            readOnlyRootFilesystem: true
            capabilities:
              drop: [ALL]"""


def container(name, image, command, resources, env="", env_from="", mounts=""):
    return f"""        - name: {name}
          image: {image}
          command: {command}
{env_from}{env}          securityContext:
{SECURITY}
          resources:
            requests:
              cpu: {resources[0]}
              memory: {resources[1]}
            limits:
              memory: {resources[2]}
          volumeMounts:
{mounts}"""


SCRIPTS_MOUNT = "            - name: scripts\n              mountPath: /opt/oj/backup\n              readOnly: true\n"
TLS_MOUNT = "            - name: tls\n              mountPath: /etc/oj/tls\n              readOnly: true\n"
TMP_MOUNT = "            - name: tmp\n              mountPath: /tmp\n"
STAGING_MOUNT = "            - name: staging\n              mountPath: /staging\n"


def secret_ref(name, prefix=None):
    """An envFrom entry: the Secret's keys as variables, each name prefixed with `prefix` when there is one."""
    lead = f"prefix: {prefix}\n              " if prefix else ""
    return f"            - {lead}secretRef:\n                name: {name}\n"


def backup():
    dump = container("dump", POSTGRES, "[/bin/bash, /opt/oj/backup/dump.sh]", ("50m", "64Mi", "256Mi"),
                     env="          env:\n            - name: HOME\n              value: /tmp\n",
                     env_from="          envFrom:\n" + secret_ref("env-identity-db", "IDENTITY_") + secret_ref("env-problem", "PROBLEM_")
                     + secret_ref("env-submission", "SUBMISSION_"),
                     mounts=SCRIPTS_MOUNT + TLS_MOUNT + STAGING_MOUNT + TMP_MOUNT)
    mirror = container("mirror", MINIO, "[/bin/bash, /opt/oj/backup/mirror.sh]", ("20m", "64Mi", "256Mi"),
                       env_from="          envFrom:\n" + secret_ref("minio-init"),
                       mounts=SCRIPTS_MOUNT + TLS_MOUNT + STAGING_MOUNT + TMP_MOUNT)
    restic = container("restic", RESTIC, "[/bin/sh, /opt/oj/backup/restic.sh]", ("20m", "64Mi", "384Mi"),
                       env_from="          envFrom:\n" + secret_ref("restic"),
                       mounts=SCRIPTS_MOUNT + "            - name: staging\n              mountPath: /staging\n              readOnly: true\n" + TMP_MOUNT)
    return f"""apiVersion: batch/v1
kind: CronJob
metadata:
  name: backup
spec:
  schedule: "0 3 * * *"
  timeZone: Asia/Ho_Chi_Minh
  concurrencyPolicy: Forbid
  startingDeadlineSeconds: 3600
  successfulJobsHistoryLimit: 3
  failedJobsHistoryLimit: 3
  jobTemplate:
    spec:
      activeDeadlineSeconds: 3600
      backoffLimit: 0
      template:
        metadata:
          labels:
            app: backup
        spec:
          enableServiceLinks: false
          automountServiceAccountToken: false
          restartPolicy: Never
          securityContext:
            # uid 999 like the databases and the drill: restic keeps the files' modes (0600), so what restores a snapshot
            # (the drill) must be the uid that wrote it
            runAsUser: 999
            runAsGroup: 999
            runAsNonRoot: true
            fsGroup: 999
            seccompProfile:
              type: RuntimeDefault
          initContainers:
{indent(dump, 4)}{indent(mirror, 4)}          containers:
{indent(restic, 4)}          volumes:
            - name: scripts
              configMap:
                name: backup-scripts
                defaultMode: 0555
            - name: tls
              secret:
                secretName: tls-backup
                defaultMode: 0440
            # dumps hold password hashes; the volume goes with the pod
            - name: staging
              emptyDir:
                sizeLimit: 4Gi
            - name: tmp
              emptyDir:
                sizeLimit: 256Mi
"""


def indent(text, n):
    return "".join((" " * n + line) if line.strip() else line for line in text.splitlines(True))


def drill():
    restore = container("restic-restore", RESTIC, '[/bin/sh, -c, "export HOME=/tmp RESTIC_CACHE_DIR=/tmp/restic-cache; restic restore latest --no-lock --host oj --target /restore --include /staging"]',
                        ("20m", "64Mi", "384Mi"), env_from="          envFrom:\n" + secret_ref("restic"),
                        mounts="            - name: restore\n              mountPath: /restore\n" + TMP_MOUNT)
    verify = container("verify", POSTGRES, "[/bin/bash, /opt/oj/backup/drill.sh]", ("50m", "128Mi", "512Mi"),
                       mounts=SCRIPTS_MOUNT + "            - name: restore\n              mountPath: /restore\n              readOnly: true\n" + TMP_MOUNT)
    return f"""---
apiVersion: batch/v1
kind: CronJob
metadata:
  name: restore-drill
spec:
  # never runs by itself: kubectl -n oj create job drill-$(date +%s) --from=cronjob/restore-drill (k3s/scripts/restore-drill.sh does it)
  suspend: true
  schedule: "0 0 1 1 *"
  concurrencyPolicy: Forbid
  successfulJobsHistoryLimit: 3
  failedJobsHistoryLimit: 3
  jobTemplate:
    spec:
      activeDeadlineSeconds: 1800
      backoffLimit: 0
      template:
        metadata:
          labels:
            app: restore-drill
        spec:
          enableServiceLinks: false
          automountServiceAccountToken: false
          restartPolicy: Never
          securityContext:
            runAsUser: 999
            runAsGroup: 999
            runAsNonRoot: true
            fsGroup: 999
            seccompProfile:
              type: RuntimeDefault
          initContainers:
{indent(restore, 4)}          containers:
{indent(verify, 4)}          volumes:
            - name: scripts
              configMap:
                name: backup-scripts
                defaultMode: 0555
            - name: restore
              emptyDir:
                sizeLimit: 4Gi
            - name: tmp
              emptyDir:
                sizeLimit: 512Mi
"""


def main():
    scripts = {os.path.basename(p): read(os.path.relpath(p, ROOT)) for p in sorted(glob.glob(os.path.join(ROOT, "k3s", "backup", "*.sh")))}
    scripts["lib.sh"] = read("backup/lib.sh")
    cm = "apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: backup-scripts\ndata:\n" + "".join(f"  {k}: {block(v, 4)}\n" for k, v in sorted(scripts.items()))
    return HEADER + cm + "---\n" + backup() + drill()


if __name__ == "__main__":
    sys.stdout.write(main())
