#!/usr/bin/env python3
"""Generated parts of k3s/base/observability, so the monitoring on K3s is the compose stack's own files and cannot drift:

  gen_observability.py config      the ConfigMaps: prometheus.yml (compose's, minus the host-level jobs, with the judge pods found
                                   through the Kubernetes API) with alerts.yml, alertmanager/, grafana/ and exporter-web.yml
  gen_observability.py exporters   a Service and a Deployment for each of the three postgres-exporters, redis-exporter and
                                   kafka-exporter (the arguments, environment and memory limit of docker-compose.yml)
  gen_observability.py policies    the NetworkPolicies that let Prometheus scrape, Grafana query Prometheus and each exporter
                                   read the one thing it exports

  python3 k3s/scripts/gen_observability.py config > k3s/base/observability/config.yaml

tests/k3s-observability.test.sh compares the result with the committed files and each ConfigMap with its source.
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
HEADER = "# Generated by k3s/scripts/gen_observability.py {target}: edit its sources (or the script), not this file.\n"

# prometheus.yml jobs that read the host (hostPath, hostPID) and so cannot run in a namespace at Pod Security `baseline`
HOST_JOBS = ("node-exporter", "cadvisor")

SCRAPE_TLS = "{ca_file: /etc/oj/tls/ca.crt, cert_file: /etc/oj/tls/tls.crt, key_file: /etc/oj/tls/tls.key, server_name: %s}"

POD_JOB = """  - job_name: {job}
    # One target per pod of the Deployment {app}: found through the Kubernetes API, so a pod KEDA adds is scraped at once and a
    # deleted one drops out. {down} asks whether any is still up. The targets are pod IPs, so server_name names the host the
    # worker's certificate is checked against; only the worker's metrics port is a target (the sandbox declares ports too).
    scheme: https
    tls_config: {tls}
    kubernetes_sd_configs:
      - role: pod
        namespaces:
          names: [oj]
        selectors:
          - role: pod
            label: app={app}
    relabel_configs:
      - source_labels: [__meta_kubernetes_pod_container_port_number]
        regex: "9100"
        action: keep
      - source_labels: [__meta_kubernetes_pod_phase]
        regex: Running
        action: keep
      - source_labels: [__meta_kubernetes_pod_name]
        target_label: pod
"""

KSM_JOB = """  # kube-state-metrics has no TLS: plain HTTP inside the namespace (documented exception, like cAdvisor in compose). It is
  # where JudgePodOOMKilled's series come from.
  - job_name: kube-state-metrics
    static_configs:
      - targets: ['kube-state-metrics:8080']
"""


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return f.read()


def block(text, indent):
    lines = text.rstrip("\n").split("\n")
    return "|\n" + "\n".join((" " * indent + line) if line else "" for line in lines)


def configmap(name, files):
    body = "".join(f"  {key}: {block(text, 4)}\n" for key, text in files)
    return f"apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: {name}\ndata:\n{body}"


def q(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def prometheus_yml():
    """compose's prometheus.yml: every job kept as it is (the services have the same names as Services), the worker jobs
    rewritten for pod discovery, the host jobs dropped, kube-state-metrics added. A job's own comment lines (two-space
    indent, directly above its `- job_name:`) travel with it; a dropped job hands its comment to the next kept one."""
    text = read("prometheus.yml")
    head, _, rest = text.partition("\nscrape_configs:\n")
    blocks, current, preamble = [], None, []
    for line in rest.split("\n"):
        m = re.match(r"  - job_name: (\S+)", line)
        if m:
            current = {"name": m.group(1), "preamble": preamble, "lines": [line]}
            blocks.append(current)
            preamble = []
        elif re.match(r"  #", line) and (current is None or current["lines"] and current["lines"][-1] == ""):
            preamble.append(line)
        elif current is not None:
            current["lines"].append(line)
    out, carry = [], []
    for b in blocks:
        body = list(b["lines"])
        while body and body[-1] == "":
            body.pop()
        if b["name"] in HOST_JOBS:
            if b["name"] == "node-exporter":
                carry = b["preamble"]
            continue
        if b["name"] in ("judge-worker", "run-worker"):
            app, down = ("judge", "JudgeWorkerDown") if b["name"] == "judge-worker" else ("run-judge", "RunWorkerDown")
            out.append(POD_JOB.format(job=b["name"], app=app, down=down, tls=SCRAPE_TLS % b["name"]).rstrip("\n"))
            continue
        out.append("\n".join(carry + b["preamble"] + body))
        carry = []
    # compose mounts the certificate from a volume subpath; here it is the Secret tls-prometheus
    body = "\n\n".join(out).replace("from the tls volume (subpath prometheus)", "from the tls volume (the Secret tls-prometheus)")
    return head + "\nscrape_configs:\n" + body + "\n\n" + KSM_JOB


def config():
    grafana_dashboards = sorted(f for f in os.listdir(os.path.join(ROOT, "grafana", "dashboards")) if f.endswith(".json"))
    return (HEADER.format(target="config")
            + configmap("prometheus-config", [("prometheus.yml", prometheus_yml()), ("alerts.yml", read("alerts.yml"))])
            + "---\n" + configmap("alertmanager-config", [("render.sh", read("alertmanager/render.sh")),
                                                         ("telegram.tmpl", read("alertmanager/telegram.tmpl"))])
            + "---\n" + configmap("grafana-provisioning", [("datasources.yml", read("grafana/provisioning/datasources/datasources.yml")),
                                                          ("dashboards.yml", read("grafana/provisioning/dashboards/dashboards.yml"))])
            + "---\n" + configmap("grafana-dashboards", [(f, read(f"grafana/dashboards/{f}")) for f in grafana_dashboards])
            + "---\n" + configmap("exporter-web", [("exporter-web.yml", exporter_web())]))


def exporter_web():
    """The `exporter-web` config of docker-compose.yml, as the file the exporters read."""
    text = read("docker-compose.yml")
    m = re.search(r"^  exporter-web:\n(?:    #.*\n)*    content: \|\n((?:      .*\n)+)", text, re.M)
    if not m:
        sys.exit("gen_observability.py: no exporter-web config in docker-compose.yml")
    return "".join(line[6:] + "\n" for line in m.group(1).rstrip("\n").split("\n"))


PG_URI = "{db}:5432/postgres?sslmode=verify-full&sslrootcert=/etc/oj/tls/ca.crt&sslcert=/etc/oj/tls/tls.crt&sslkey=/etc/oj/tls/tls.key"
KAFKA_ARGS = ["--kafka.server=kafka:29092", "--tls.enabled", "--tls.server-name=kafka", "--tls.ca-file=/etc/oj/tls/ca.crt",
              "--tls.cert-file=/etc/oj/tls/tls.crt", "--tls.key-file=/etc/oj/tls/tls.key", "--server.tls.enabled",
              "--server.tls.mutual-auth-enabled", "--server.tls.ca-file=/etc/oj/tls/ca.crt", "--server.tls.cert-file=/etc/oj/tls/tls.crt",
              "--server.tls.key-file=/etc/oj/tls/tls.key"]
REDIS_ARGS = ["-redis.addr=rediss://redis:6379", "-tls-ca-cert-file=/etc/oj/tls/ca.crt", "-tls-client-cert-file=/etc/oj/tls/tls.crt",
              "-tls-client-key-file=/etc/oj/tls/tls.key", "-tls-server-cert-file=/etc/oj/tls/tls.crt",
              "-tls-server-key-file=/etc/oj/tls/tls.key", "-tls-server-ca-cert-file=/etc/oj/tls/ca.crt"]
PG_IMAGE = "prometheuscommunity/postgres-exporter:v0.20.1"
EXPORTERS = [dict(name=f"{db}-exporter", image=PG_IMAGE, port=9187, uid=65534, args=["--web.config.file=/etc/oj/exporter-web.yml"],
                  web=True, db=db) for db in ("identity-db", "problem-db", "submission-db")] + [
    dict(name="redis-exporter", image="oliver006/redis_exporter:v1.96.0", port=9121, uid=59000, args=REDIS_ARGS, web=False),
    dict(name="kafka-exporter", image="danielqsj/kafka-exporter:v1.11.0", port=9308, uid=65534, args=KAFKA_ARGS, web=False)]


def exporters():
    out = [HEADER.format(target="exporters")]
    for e in EXPORTERS:
        name = e["name"]
        args = "".join(f"            - {q(a)}\n" for a in e["args"])
        env = ""
        if e.get("db"):
            env = ("          env:\n"
                   f"            - name: DATA_SOURCE_URI\n              value: {q(PG_URI.format(db=e['db']))}\n"
                   "            - name: DATA_SOURCE_USER\n              value: oj_monitor\n"
                   "            - name: DATA_SOURCE_PASS\n              valueFrom:\n                secretKeyRef:\n"
                   "                  name: pg-monitor\n                  key: PG_MONITOR_PASSWORD\n")
        web_mount = ("            - name: exporter-web\n              mountPath: /etc/oj/exporter-web.yml\n"
                     "              subPath: exporter-web.yml\n              readOnly: true\n") if e["web"] else ""
        web_volume = "        - name: exporter-web\n          configMap:\n            name: exporter-web\n" if e["web"] else ""
        out.append(f"""---
apiVersion: v1
kind: Service
metadata:
  name: {name}
  labels:
    app: {name}
spec:
  selector:
    app: {name}
  ports:
    - name: metrics
      port: {e["port"]}
---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: {name}
  labels:
    app: {name}
spec:
  replicas: 1
  strategy:
    type: RollingUpdate
    rollingUpdate:
      maxSurge: 1
      maxUnavailable: 0
  selector:
    matchLabels:
      app: {name}
  template:
    metadata:
      labels:
        app: {name}
    spec:
      enableServiceLinks: false
      automountServiceAccountToken: false
      securityContext:
        runAsUser: {e["uid"]}
        runAsGroup: {e["uid"]}
        runAsNonRoot: true
        fsGroup: {e["uid"]}
        seccompProfile:
          type: RuntimeDefault
      containers:
        - name: {name}
          image: {e["image"]}
          args:
{args}{env}          ports:
            - name: metrics
              containerPort: {e["port"]}
          securityContext:
            allowPrivilegeEscalation: false
            readOnlyRootFilesystem: true
            capabilities:
              drop: [ALL]
          resources:
            requests:
              cpu: 10m
              memory: 24Mi
            limits:
              memory: 64Mi
          # the listener answers only a client certificate, so a probe can only ask whether the port is open
          readinessProbe:
            tcpSocket:
              port: metrics
            periodSeconds: 10
          livenessProbe:
            tcpSocket:
              port: metrics
            periodSeconds: 30
            failureThreshold: 6
          volumeMounts:
            - name: tls
              mountPath: /etc/oj/tls
              readOnly: true
{web_mount}      volumes:
        - name: tls
          secret:
            secretName: tls-{name}
            defaultMode: 0440
{web_volume}""")
    return "".join(out)


def policy(name, target, port, source):
    """An ingress policy: pods of `target` (an app, or several) accept `port` from pods of the app `source`."""
    if isinstance(target, str):
        selector = f"    matchLabels:\n      app: {target}\n"
    else:
        selector = ("    matchExpressions:\n      - key: app\n        operator: In\n        values:\n"
                    + "".join(f"          - {t}\n" for t in target))
    return f"""---
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: {name}
spec:
  podSelector:
{selector}  policyTypes: [Ingress]
  ingress:
    - from:
        - podSelector:
            matchLabels:
              app: {source}
      ports:
        - port: {port}
"""


def policies():
    out = [HEADER.format(target="policies").rstrip("\n") + "\n# Prometheus scrapes what it may (the actuators, the judge pods' metrics, the exporters, kube-state-metrics, Alertmanager); Grafana\n# queries Prometheus; each exporter reads the one database, Redis or Kafka it exports. Added to the allow-to-* policies of base/network.\n"]
    p = lambda *a: out.append(policy(*a))
    p("allow-prometheus-to-actuators", ["identity-service", "problem-service", "submission-service", "api-gateway"], 8081, "prometheus")
    p("allow-prometheus-to-judge-metrics", ["judge", "run-judge"], 9100, "prometheus")
    p("allow-prometheus-to-db-exporters", [e["name"] for e in EXPORTERS if e.get("db")], 9187, "prometheus")
    p("allow-prometheus-to-redis-exporter", "redis-exporter", 9121, "prometheus")
    p("allow-prometheus-to-kafka-exporter", "kafka-exporter", 9308, "prometheus")
    p("allow-prometheus-to-kube-state-metrics", "kube-state-metrics", 8080, "prometheus")
    p("allow-prometheus-to-alertmanager", "alertmanager", 9093, "prometheus")
    p("allow-grafana-to-prometheus", "prometheus", 9090, "grafana")
    for e in EXPORTERS:
        if e.get("db"):
            p(f"allow-{e['name']}-to-{e['db']}", e["db"], 5432, e["name"])
    p("allow-redis-exporter-to-redis", "redis", 6379, "redis-exporter")
    p("allow-kafka-exporter-to-kafka", "kafka", 29092, "kafka-exporter")
    return "".join(out)


if __name__ == "__main__":
    targets = {"config": config, "exporters": exporters, "policies": policies}
    if len(sys.argv) != 2 or sys.argv[1] not in targets:
        sys.exit("usage: gen_observability.py config|exporters|policies")
    sys.stdout.write(targets[sys.argv[1]]())
