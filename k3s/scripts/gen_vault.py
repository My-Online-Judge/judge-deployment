#!/usr/bin/env python3
"""k3s/components/vault/secrets.yaml: one VaultStaticSecret for each Secret of k3s/scripts/secret_map.py, so the Vault Secrets Operator
writes the same Secret names (and keys, which vault.sh seed took from the same table) the pods read today.

  python3 k3s/scripts/gen_vault.py > k3s/components/vault/secrets.yaml

tests/k3s-vault.test.sh compares the result with the committed file, and RESTART with the Deployments that read each Secret.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import secret_map

# The Deployments that restart when the Secret changes in Vault (a running process keeps the value it started with). Never a database or
# MinIO: changing POSTGRES_PASSWORD or MINIO_ROOT_PASSWORD in the environment does not change the password stored in their data.
RESTART = {
    "env-identity": ["identity-service"],
    "env-problem": ["problem-service"],
    "env-submission": ["submission-service"],
    "minio-problem": ["problem-service"],
    "minio-worker": ["judge"],
    "judge-token": ["judge", "run-judge", "submission-service"],
    "pg-monitor": ["identity-db-exporter", "problem-db-exporter", "submission-db-exporter"],
    "grafana-admin": ["grafana"],
    "alertmanager-telegram": ["alertmanager"],
}

print("# Generated by k3s/scripts/gen_vault.py from k3s/scripts/secret_map.py: edit those, not this file.")
for name, _, _ in secret_map.SECRETS:
    lines = ["---", "apiVersion: secrets.hashicorp.com/v1beta1", "kind: VaultStaticSecret", "metadata:", f"  name: {name}", "spec:",
             "  vaultAuthRef: vault", "  mount: kv", "  type: kv-v2", f"  path: {name}", "  refreshAfter: 60s",
             "  destination:", f"    name: {name}", "    create: true", "    overwrite: true",
             # no `_raw` key (the whole Vault response as JSON): the Secret has exactly the keys env-to-secrets.sh gives it
             "    transformation:", "      excludeRaw: true"]
    if RESTART.get(name):
        lines.append("  rolloutRestartTargets:")
        lines += [f"    - kind: Deployment\n      name: {target}" for target in RESTART[name]]
    print("\n".join(lines))
